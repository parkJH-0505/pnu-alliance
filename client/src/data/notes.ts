export function getFeatured(): Note | undefined {
  return NOTES.find((n) => n.featured) || NOTES[0];
}

export function getOthers(): Note[] {
  const featured = getFeatured();
  return NOTES.filter((n) => n.slug !== featured?.slug);
}

export function findBySlug(slug: string): Note | undefined {
  return NOTES.find((n) => n.slug === slug);
}
